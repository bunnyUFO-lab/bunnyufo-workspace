// Keeps a workspace's Just the Docs site in step with its workspace.json, the card
// registry. It writes navigation front matter into each active card's Markdown pages
// (bodies and extra keys are kept), regenerates the home and category pages and gallery
// pages, and lists archived card folders in _config.yml's exclude.
// The workspace is the active one (see server/workspaces.mjs) unless chosen:
// Usage: node scripts/docs-sync.mjs [--check] [--content <folder|id> | --template]
//   --check changes nothing and exits 1 if out of date; --template uses the app's workspace/.
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readGallery, renderGallery } from './docs-gallery.mjs';
import { defaultRegistryFile, resolveWorkspace } from '../server/workspaces.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
/** The app's own workspace/: the starter examples. */
export const templateSite = path.join(root, 'workspace');
export const MANAGED = ['title', 'parent', 'grand_parent', 'nav_order', 'has_children', 'description', 'render_with_liquid'];
const GENERATED = '<!-- Generated by `npm run docs:sync` from workspace/workspace.json. Edit the registry, not this page. -->';
const BASE_EXCLUDE = ['Gemfile', 'Gemfile.lock', 'docker-compose.yml', 'workspace.json', 'README.md', 'vendor', '.jekyll-cache', '_site'];
const FRONT_MATTER = /^---\r?\n((?:[\s\S]*?\r?\n)?)---[ \t]*(?:\r?\n|$)/;

export function splitFrontMatter(text) {
  const start = text.charCodeAt(0) === 0xfeff ? 1 : 0; // byte order mark
  const match = FRONT_MATTER.exec(text.slice(start));
  if (!match) return { lines: [], body: text };
  return { lines: match[1].split(/\r?\n/).slice(0, -1), body: text.slice(start + match[0].length) };
}

const scalar = value => typeof value === 'string' ? JSON.stringify(value) : String(value);

/** Replace the managed keys (and any key in `values`), keep every other front matter line and the body. */
export function setFrontMatter(text, values) {
  const { lines, body } = splitFrontMatter(text);
  const owned = new Set([...MANAGED, ...Object.keys(values)]);
  const kept = [];
  for (let index = 0; index < lines.length; index++) {
    const key = /^([A-Za-z_][\w-]*)\s*:/.exec(lines[index])?.[1];
    if (key && owned.has(key)) {
      while (index + 1 < lines.length && /^[ \t]/.test(lines[index + 1])) index++;
      continue;
    }
    kept.push(lines[index]);
  }
  const order = [...MANAGED, ...Object.keys(values).filter(key => !MANAGED.includes(key))];
  const written = order.filter(key => values[key] !== undefined).map(key => `${key}: ${scalar(values[key])}`);
  return ['---', ...written, ...kept, '---', ''].join('\n') + body;
}

export const categoryTitle = id => String(id || 'other').split('-').map(word => word.charAt(0).toUpperCase() + word.slice(1)).join(' ');
const isActive = card => card.status !== 'archived';
const byRelevance = (a, b) => Number(!!b.pinned) - Number(!!a.pinned) || String(b.updated).localeCompare(String(a.updated)) || a.title.localeCompare(b.title);
const markdownSteps = card => (card.steps ?? []).filter(step => /\.md$/i.test(step.path));
const posix = value => value.split(path.sep).join('/');
const cardLink = (card, from, site) => {
  const target = markdownSteps(card)[0] ?? card.steps?.[0];
  return target ? posix(path.relative(from, path.join(site, card.folder, target.path))) : '';
};
const listItem = (card, from, site) => `- [${card.title}](${cardLink(card, from, site)})${card.pinned ? ' (pinned)' : ''}${card.status === 'done' ? ' (done)' : ''}: ${card.description || ''} Updated ${card.updated}.`;

/** Every file the site needs, as { file: absolute path, content }. Existing pages are read for their bodies. */
export async function plan(entities, site = templateSite) {
  const outputs = [];
  const active = entities.filter(isActive).sort(byRelevance);
  const categories = [...new Set(active.map(card => card.category || 'other'))].sort((a, b) => categoryTitle(a).localeCompare(categoryTitle(b)));

  const home = [GENERATED, '', '# bunnyUFO Workspace', '', 'Cards, research and asset notes. The Workspace app and this site read the same Markdown pages.', ''];
  const pinned = active.filter(card => card.pinned);
  if (pinned.length) home.push('## Pinned', '', ...pinned.map(card => listItem(card, site, site)), '');
  for (const category of categories) {
    home.push(`## ${categoryTitle(category)}`, '', ...active.filter(card => (card.category || 'other') === category).map(card => listItem(card, site, site)), '');
  }
  outputs.push({ file: path.join(site, 'index.md'), content: setFrontMatter(home.join('\n'), { title: 'Home', nav_order: 1, layout: 'home', render_with_liquid: false }) });

  categories.forEach((category, index) => {
    const folder = path.join(site, 'categories');
    const cards = active.filter(card => (card.category || 'other') === category);
    const body = [GENERATED, '', `# ${categoryTitle(category)}`, '', ...cards.map(card => listItem(card, folder, site)), ''].join('\n');
    outputs.push({ file: path.join(folder, `${category}.md`), content: setFrontMatter(body, { title: categoryTitle(category), nav_order: index + 2, has_children: true, render_with_liquid: false }) });
  });

  for (const category of categories) {
    const cards = active.filter(card => (card.category || 'other') === category);
    for (const [cardIndex, card] of cards.entries()) {
      const pages = markdownSteps(card);
      for (const [index, step] of pages.entries()) {
        const file = path.join(site, card.folder, step.path);
        let text = await readFile(file, 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; });
        // A gallery page's body is generated from the gallery.json beside it; its front matter is kept.
        if (/^gallery\.md$/i.test(step.path)) {
          const gallery = await readGallery(path.join(site, card.folder));
          const { lines } = splitFrontMatter(text);
          if (gallery) text = (lines.length ? ['---', ...lines, '---', ''].join('\n') : '') + renderGallery(gallery);
        }
        const values = index === 0
          ? { title: card.title, parent: categoryTitle(category), nav_order: cardIndex + 1, has_children: pages.length > 1 ? true : undefined, description: card.description || undefined, render_with_liquid: false }
          : { title: step.name, parent: card.title, grand_parent: categoryTitle(category), nav_order: index, render_with_liquid: false };
        outputs.push({ file, content: setFrontMatter(text, values) });
      }
    }
  }

  const config = path.join(site, '_config.yml');
  const archived = entities.filter(card => !isActive(card)).map(card => card.folder).sort();
  const block = ['# BEGIN docs-sync: generated from workspace.json by `npm run docs:sync`; do not edit by hand', 'exclude:',
    ...[...BASE_EXCLUDE, ...archived].map(entry => `  - ${JSON.stringify(entry)}`), '# END docs-sync'].join('\n');
  const current = await readFile(config, 'utf8');
  const pattern = /# BEGIN docs-sync[^\n]*\n[\s\S]*?# END docs-sync/;
  if (!pattern.test(current)) throw new Error(`${config} is missing its "# BEGIN docs-sync" ... "# END docs-sync" block`);
  outputs.push({ file: config, content: current.replace(pattern, block) });
  return outputs;
}

async function staleCategoryPages(outputs, site) {
  const folder = path.join(site, 'categories');
  const wanted = new Set(outputs.map(output => output.file));
  const names = await readdir(folder).catch(() => []);
  const stale = [];
  for (const name of names.filter(name => name.endsWith('.md'))) {
    const file = path.join(folder, name);
    if (!wanted.has(file) && (await readFile(file, 'utf8')).includes(GENERATED)) stale.push(file);
  }
  return stale;
}

/** The workspace folder to sync: `content` (folder or id), the template, or the active workspace. */
export async function resolveSite({ content, template = false } = {}) {
  if (template) return templateSite;
  return (await resolveWorkspace({ appRepo: root, content, registryFile: defaultRegistryFile() })).root;
}

export async function sync({ check = false, site, content, template = false } = {}) {
  site = path.resolve(site || await resolveSite({ content, template }));
  const { entities } = JSON.parse(await readFile(path.join(site, 'workspace.json'), 'utf8'));
  const outputs = await plan(entities, site);
  const changed = [];
  for (const { file, content } of outputs) {
    const current = await readFile(file, 'utf8').catch(() => null);
    // Windows checkouts (core.autocrlf) hold CRLF copies of the same text.
    if (current?.replace(/\r\n/g, '\n') === content.replace(/\r\n/g, '\n')) continue;
    changed.push(posix(path.relative(site, file)));
    if (!check) { await mkdir(path.dirname(file), { recursive: true }); await writeFile(file, content); }
  }
  for (const file of await staleCategoryPages(outputs, site)) {
    changed.push(`${posix(path.relative(site, file))} (removed)`);
    if (!check) await rm(file);
  }
  return changed;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const contentAt = args.indexOf('--content');
  const site = await resolveSite({ content: contentAt >= 0 ? args[contentAt + 1] : undefined, template: args.includes('--template') });
  const changed = await sync({ check, site });
  if (check && changed.length) {
    console.error(`Docs site is out of date with workspace.json; run npm run docs:sync:\n  ${changed.join('\n  ')}`);
    process.exit(1);
  }
  console.log(changed.length ? `${check ? 'Would update' : 'Updated'} (${site}):\n  ${changed.join('\n  ')}` : `Docs site is in sync with workspace.json (${site}).`);
}
