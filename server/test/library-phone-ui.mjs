// Run after npm run build. The Library on a phone and the way back from a card, through a real browser:
// one project filter that takes several (kept on the device, no history step, one sheet entry), the Recent | By project toggle
// (remembered, no history step), no sideways scroll at 360 px even with the search focused, one focus ring on the search field,
// the tab bar on a card with Library lit, a Back button of at least 44 px that says where it goes, and Back and the Library tab
// both returning to the list with its projects, search and scroll as they were.
import { chromium } from '@playwright/test';
import { ms } from './ui-timeouts.mjs';
import assert from 'node:assert/strict';
import { startHubFixture } from './hub-fixture.mjs';
import { entryOf, hashOf, libraryFilter, nav, noSideways, openLibrary, pickProject, projectRows, withProjectList } from './shell-helpers.mjs';

const step = name => console.log(`- ${name}`);
const channel = process.env.BUW_TEST_BROWSER || 'msedge';
const fixture = await startHubFixture({ hermes: true, secondSection: true, thirdSection: 40 });
const browser = await chromium.launch({ headless: true, channel });
const contexts = [];
const errors = [];
const open = async (viewport, options = {}) => {
  const context = await browser.newContext({ viewport, serviceWorkers: 'block', hasTouch: viewport.width < 900, ...options });
  contexts.push(context);
  const page = await context.newPage();
  page.setDefaultTimeout(ms(15000));
  page.on('pageerror', error => errors.push(error.message));
  return page;
};
const rows = page => page.locator('[data-library] .lib-row');
const projectsShown = async page => [...new Set(await rows(page).evaluateAll(list => list.map(row => row.dataset.project)))].sort();
const label = async page => (await libraryFilter(page).innerText()).trim();
const arrange = (page, name) => page.locator('[data-library] .ui-seg.lib-arrange button', { hasText: new RegExp('^' + name) });
const view = (page, name) => page.locator('[data-library] .ui-seg:not(.lib-arrange) button', { hasText: new RegExp('^' + name) });
const heads = page => page.locator('[data-library] .lib-head h2').allInnerTexts();
const fitsAcross = page => page.evaluate(() => ['.lib', '.lib-bar', '.lib-search', '.lib-scroll'].map(selector => { const el = document.querySelector(selector); return el ? [selector, el.scrollWidth, el.clientWidth] : null; }).filter(Boolean));
const library = async page => { await page.goto(`${fixture.url}#/~hub/today`); await page.locator('.hub[data-screen="today"]').waitFor(); await nav(page, 'library'); await openLibrary(page); };

try {
  step('360 px: the filter and the toggle share one line, nothing scrolls sideways, also with the search focused');
  const phone = await open({ width: 360, height: 740 });
  await library(phone);
  assert.equal(await phone.locator('[data-library] .ui-chips').count(), 0, 'no row of chips to scroll sideways');
  assert.equal(await label(phone), 'All projects');
  const bar = await phone.locator('[data-library] .lib-bar').boundingBox();
  const filterBox = await libraryFilter(phone).boundingBox();
  const toggleBox = await phone.locator('[data-library] .lib-arrange').boundingBox();
  assert.ok(Math.abs(filterBox.y - toggleBox.y) < 8 && filterBox.x + filterBox.width <= toggleBox.x + 1, 'the filter and the toggle sit on one line');
  assert.ok(toggleBox.x + toggleBox.width <= 360 && bar.x + bar.width <= 360, 'the line fits 360 px');
  await noSideways(phone, 'Library at 360');
  for (const [selector, scroll, client] of await fitsAcross(phone)) assert.ok(scroll <= client, `${selector} does not overflow (${scroll} > ${client})`);
  await phone.locator('[data-library] .lib-search input').focus();
  await phone.keyboard.type('gir');
  await noSideways(phone, 'Library at 360 with the search focused');
  for (const [selector, scroll, client] of await fitsAcross(phone)) assert.ok(scroll <= client, `${selector} does not overflow with the search focused (${scroll} > ${client})`);
  assert.equal(await phone.evaluate(() => [document.querySelector('.lib').scrollLeft, document.querySelector('.main').scrollLeft, document.scrollingElement.scrollLeft].join()), '0,0,0', 'nothing was panned sideways');
  assert.equal(await phone.locator('[data-library] .lib-top h1, [data-library] .ui-top h1').evaluate(el => el.getBoundingClientRect().left >= 0), true, 'the title is where it belongs');
  assert.ok(await phone.locator('[data-library] .lib-search input').evaluate(el => parseFloat(getComputedStyle(el).fontSize) >= 16), 'a field of 16 px or more, so a phone does not zoom in on it');
  await phone.locator('[data-library] .lib-search input').fill('');
  await phone.locator('[data-library] .lib-search input').blur();

  step('two projects: only their cards, the sheet is one entry, picking adds none, a reload keeps them, All clears them');
  const before = await entryOf(phone);
  await libraryFilter(phone).click();
  const list = phone.locator('.ui-sheet [data-project-list]');
  await list.waitFor();
  assert.match(await hashOf(phone), /\/~o$/, 'opening the list is a sheet entry');
  const names = await list.locator('.lib-pick-name').allInnerTexts();
  assert.deepEqual(names.slice(0, 1), ['All projects'], 'All projects comes first');
  assert.ok(names.includes('Two') && names.includes('Three') && names.includes('One'));
  await list.locator('label.lib-pick', { hasText: /^Two/ }).click();
  assert.ok(await list.isVisible(), 'a tap leaves the list open');
  await list.locator('label.lib-pick', { hasText: /^Three/ }).click();
  assert.ok(await list.isVisible(), 'and still open');
  assert.deepEqual(await projectsShown(phone), ['three', 'two'], 'the rows behind updated');
  assert.equal(await list.locator('label.lib-pick', { hasText: /^Two/ }).locator('input').isChecked(), true);
  await phone.goBack();
  await list.waitFor({ state: 'detached' });
  assert.deepEqual(await entryOf(phone), before, 'picking added no history entry; the sheet took its own off');
  assert.equal(await label(phone), '2 projects');
  await phone.reload();
  await phone.locator('[data-library] .lib-scroll').waitFor();
  assert.equal(await label(phone), '2 projects', 'a reload keeps the picks');
  assert.deepEqual(await projectsShown(phone), ['three', 'two']);
  await pickProject(phone, 'Three');
  assert.equal(await label(phone), 'Two', 'one pick is the project name');
  assert.match(await phone.evaluate(() => localStorage.getItem('buw.project')), /two/, 'one pick is the address (kept as it was)');
  await pickProject(phone, 'Two');
  assert.equal(await label(phone), 'All projects', 'unticking the last one means all');
  await pickProject(phone, 'Two');
  await pickProject(phone, 'Three');
  await pickProject(phone, 'All projects');
  assert.equal(await label(phone), 'All projects', 'All projects clears the picks');
  assert.ok((await projectsShown(phone)).length >= 3);

  step('the list: counts follow the search, projects with nothing under it go last and dimmed, still tappable');
  await phone.locator('[data-library] .lib-search input').fill('zebra');
  assert.deepEqual((await projectRows(phone)).slice(0, 2), [['All projects', 1], ['Two', 1]]);
  await libraryFilter(phone).click();
  const dim = phone.locator('.ui-sheet label.lib-pick.dim');
  assert.ok(await dim.count() >= 2, 'the empty projects are dimmed');
  assert.ok(await phone.locator('.ui-sheet label.lib-pick').last().evaluate(el => el.classList.contains('dim')), 'and last');
  const tapped = phone.locator('.ui-sheet label.lib-pick.dim').first();
  const tappedId = await tapped.getAttribute('data-pick');
  await tapped.click();
  assert.equal(await phone.locator(`.ui-sheet label.lib-pick[data-pick="${tappedId}"] input`).isChecked(), true, 'still tappable');
  await phone.locator('.ui-sheet label.lib-pick[data-pick=""]').click();
  assert.equal(await phone.locator('.ui-sheet label.lib-pick[data-pick=""] input').isChecked(), true, 'All projects clears the pick');
  await phone.goBack();
  await phone.locator('[data-library] .lib-search input').fill('');
  assert.equal(await label(phone), 'All projects');

  step('Recent | By project: Recent is the default, By project heads each project, the choice is remembered and adds no step');
  assert.equal(await arrange(phone, 'Recent').getAttribute('aria-pressed'), 'true');
  assert.deepEqual(await heads(phone), ['Recent']);
  const mark = await entryOf(phone);
  await arrange(phone, 'By project').click();
  assert.deepEqual(await entryOf(phone), mark, 'the toggle adds no step');
  const grouped = await heads(phone);
  assert.deepEqual([...grouped].sort(), ['One', 'Three', 'Two'], 'a heading per project');
  assert.deepEqual(await phone.locator('[data-library] .lib-head.project').evaluateAll(list => list.map(el => el.dataset.projectHead)), (await projectRows(phone)).slice(1).map(([name]) => ({ One: 'one', Two: 'two', Three: 'three' })[name]).filter(Boolean), 'in the filter list order');
  await phone.reload();
  await phone.locator('[data-library] .lib-scroll').waitFor();
  assert.equal(await arrange(phone, 'By project').getAttribute('aria-pressed'), 'true', 'remembered across a reload');
  await view(phone, 'Pinned').click();
  assert.equal(await arrange(phone, 'Recent').count(), 0, 'no toggle where it has no effect (Pinned)');
  await view(phone, 'Trash').click();
  assert.equal(await arrange(phone, 'Recent').count(), 0, 'nor in the Trash');
  await view(phone, 'All').click();
  await phone.locator('[data-library] .lib-search input').fill('giraffe');
  assert.equal(await arrange(phone, 'Recent').count(), 0, 'nor with a search');
  await phone.locator('[data-library] .lib-search input').fill('');
  await pickProject(phone, 'Three');
  assert.deepEqual(await heads(phone), ['Test'], 'By project with one picked is that project by category');
  await arrange(phone, 'Recent').click();
  assert.deepEqual(await heads(phone), ['Recent'], 'Recent with one picked is one run');
  await pickProject(phone, 'Three');
  await phone.reload();
  await phone.locator('[data-library] .lib-search input').waitFor();
  assert.equal(await arrange(phone, 'Recent').getAttribute('aria-pressed'), 'true');

  step('a card on a phone: the tab bar with Library lit, a Back that says Library and is 44 px or more, the header in place');
  await phone.locator('[data-library] .lib-search input').fill('giraffe');
  await pickProject(phone, 'Three');
  await pickProject(phone, 'Two');
  await view(phone, 'All').click();
  const scroller = phone.locator('[data-library] .lib-scroll');
  await scroller.evaluate(el => { el.scrollTop = 300; });
  await phone.waitForTimeout(300);
  const row = rows(phone).nth(9);
  await row.scrollIntoViewIfNeeded();
  const scrolledTo = await scroller.evaluate(el => el.scrollTop);
  assert.ok(scrolledTo > 100, `the list is scrolled (${scrolledTo})`);
  const listState = { label: await label(phone), query: 'giraffe', shown: await rows(phone).count() };
  const entryTitle = await row.locator('.lib-row-body b').innerText();
  const listEntry = await entryOf(phone);
  await row.locator('.lib-row-main').tap();
  await phone.locator('.topbar').waitFor();
  await phone.locator('.buw-markdown h1', { hasText: entryTitle }).waitFor();
  assert.equal(await phone.locator('[data-tabs]').count(), 1, 'the tab bar stays on a card');
  assert.equal(await phone.locator('[data-tabs] [data-nav="library"]').getAttribute('aria-current'), 'page', 'Library is lit');
  const back = phone.locator('.topbar [data-back]');
  const backBox = await back.boundingBox();
  assert.ok(backBox.width >= 44 && backBox.height >= 44, `Back is ${backBox.width} x ${backBox.height}`);
  assert.match((await back.innerText()).trim(), /Library/, 'and says where it goes');
  assert.ok(backBox.y >= 0 && backBox.y + backBox.height <= 120, 'at the top, in reach');
  const geometry = await phone.evaluate(() => ({ content: document.querySelector('.content').getBoundingClientRect().bottom, tabs: document.querySelector('[data-tabs]').getBoundingClientRect().top, view: innerHeight }));
  assert.ok(geometry.content <= geometry.tabs + 1, `the page ends where the tab bar begins (${JSON.stringify(geometry)})`);
  await noSideways(phone, 'a card at 360');
  await phone.setViewportSize({ width: 360, height: 400 });
  await phone.waitForTimeout(150);
  assert.equal(await phone.locator('[data-tabs]').count(), 1, 'a shorter window is not the on-screen keyboard');
  await phone.setViewportSize({ width: 360, height: 740 });

  step('Back returns to the list as it was: the same projects, search and scroll');
  await back.click();
  await scroller.waitFor();
  const afterBack = { label: await label(phone), query: await phone.locator('[data-library] .lib-search input').inputValue(), shown: await rows(phone).count() };
  assert.deepEqual(afterBack, listState, 'projects and search as they were');
  assert.deepEqual(await entryOf(phone), listEntry, 'the same history entry');
  assert.ok(Math.abs(await scroller.evaluate(el => el.scrollTop) - scrolledTo) <= 4, 'and the scroll');

  step('the Library tab from a card goes back to the entry it came from, with the same state');
  await rows(phone).nth(9).scrollIntoViewIfNeeded();
  const scrolledAgain = await scroller.evaluate(el => el.scrollTop);
  await rows(phone).nth(9).locator('.lib-row-main').tap();
  await phone.locator('.topbar').waitFor();
  await phone.locator('[data-tabs] [data-nav="library"]').tap();
  await scroller.waitFor();
  assert.deepEqual({ label: await label(phone), query: await phone.locator('[data-library] .lib-search input').inputValue(), shown: await rows(phone).count() }, listState);
  assert.deepEqual(await entryOf(phone), listEntry, 'it returned to the Library entry, not a new one');
  assert.ok(Math.abs(await scroller.evaluate(el => el.scrollTop) - scrolledAgain) <= 4, 'with the scroll');

  step('the Library tab from a card that has the Library behind it only by way of another card');
  await rows(phone).nth(9).locator('.lib-row-main').tap();
  await phone.locator('.topbar').waitFor();
  await phone.locator('.step-tab[role="tab"], .step-tab').first().waitFor();
  await phone.evaluate(() => { location.hash = '#/giraffe'; });
  await phone.locator('.buw-markdown h1', { hasText: 'Giraffe feeding' }).waitFor();
  assert.match((await phone.locator('.topbar [data-back]').innerText()).trim(), /Back/, 'behind is a card, so it says Back');
  await phone.locator('[data-tabs] [data-nav="library"]').tap();
  await scroller.waitFor();
  assert.equal(await phone.locator('[data-library] .lib-search input').inputValue(), 'giraffe', 'two steps back is still the list as it was');
  assert.deepEqual(await entryOf(phone), listEntry);

  step('the Library tab with no Library behind: the Library opens with the state it last had');
  await nav(phone, 'search');
  await phone.locator('.srch input').first().waitFor();
  await phone.evaluate(() => { location.hash = '#/giraffe'; });
  await phone.locator('.buw-markdown h1', { hasText: 'Giraffe feeding' }).waitFor();
  await phone.locator('[data-tabs] [data-nav="library"]').tap();
  await scroller.waitFor();
  assert.equal(await phone.locator('[data-library] .lib-search input').inputValue(), 'giraffe', 'the search is carried over');
  assert.equal(await label(phone), listState.label, 'and the projects');

  step('1200 px: the same list in a dialog, a keyboard can use it, one focus ring on the search, nothing sideways');
  const desk = await open({ width: 1200, height: 800 });
  await library(desk);
  await noSideways(desk, 'Library at 1200');
  await libraryFilter(desk).focus();
  await desk.keyboard.press('Enter');
  const dlist = desk.locator('.ui-sheet [data-project-list]');
  await dlist.waitFor();
  const dialog = await desk.locator('.ui-sheet').boundingBox();
  assert.ok(dialog.width < 600 && dialog.x > 200, `a dialog, not a bottom sheet (${JSON.stringify(dialog)})`);
  assert.equal(await desk.evaluate(() => document.activeElement?.closest('[data-project-list]') !== null), true, 'the keyboard starts in the list');
  await desk.keyboard.press('Tab');
  await desk.keyboard.press('Space');
  assert.notEqual(await label(desk), 'All projects', 'Tab and Space pick a project');
  await desk.keyboard.press('Escape');
  await dlist.waitFor({ state: 'detached' });
  assert.equal(await desk.evaluate(() => document.activeElement?.hasAttribute('data-project-filter')), true, 'and comes back to the button');
  await desk.locator('[data-library] .lib-search input').focus();
  const ring = await desk.evaluate(() => { const field = document.querySelector('.lib-search'); const input = field.querySelector('input'); return { field: getComputedStyle(field).boxShadow, outline: getComputedStyle(input).outlineStyle, inputShadow: getComputedStyle(input).boxShadow }; });
  assert.notEqual(ring.field, 'none', 'the field wears the ring');
  assert.equal(ring.outline, 'none', 'the input draws no square outline inside it');
  assert.equal(ring.inputShadow, 'none');
  await desk.locator('[data-library] .lib-search input').blur();
  await desk.keyboard.press('Shift+R');
  assert.equal(await arrange(desk, 'By project').getAttribute('aria-pressed'), 'true', 'Shift+R toggles Recent and By project');
  await desk.keyboard.press('Shift+R');
  assert.equal(await arrange(desk, 'Recent').getAttribute('aria-pressed'), 'true');
  await desk.keyboard.press('Control+h');
  await desk.getByText('Library: Recent or By project').waitFor();
  await desk.keyboard.press('Escape');
  await desk.locator('[data-library] .lib-search input').focus();
  await desk.keyboard.type('a');
  await noSideways(desk, 'Library at 1200 with the search focused');
  for (const [selector, scroll, client] of await fitsAcross(desk)) assert.ok(scroll <= client, `${selector} at 1200 (${scroll} > ${client})`);
  await withProjectList(desk, async () => {});

  step('zoom is not a keyboard: a pinch-zoomed card keeps its tab bar, a real keyboard hides it');
  const viewport = (page, height, scale) => page.evaluate(([h, k]) => {
    const view = window.visualViewport;
    Object.defineProperty(view, 'height', { configurable: true, get: () => h });
    Object.defineProperty(view, 'scale', { configurable: true, get: () => k });
    view.dispatchEvent(new Event('resize'));
  }, [height, scale]);
  await phone.goto(`${fixture.url}#/giraffe`);
  await phone.locator('.buw-markdown h1', { hasText: 'Giraffe feeding' }).waitFor();
  await viewport(phone, 740 - 300, 1);
  await phone.locator('[data-tabs]').waitFor({ state: 'detached' });
  await viewport(phone, 740 - 300, 2.5);
  await phone.locator('[data-tabs]').waitFor();
  await viewport(phone, 740, 1);

  step('1200 px: Escape with the project filter open closes the sheet and leaves the card open');
  const beside = await open({ width: 1200, height: 800 });
  await beside.context().addInitScript(() => { try { localStorage.setItem('buw.menuCollapsed', '0'); } catch { /* none */ } });
  await beside.goto(`${fixture.url}#/hub`);
  await beside.locator('.buw-markdown h1', { hasText: 'The hub card' }).waitFor();
  await libraryFilter(beside).click();
  await beside.locator('.ui-sheet [data-project-list]').waitFor();
  await beside.locator('.ui-sheet-h h2').click();
  await beside.keyboard.press('Escape');
  await beside.locator('.ui-sheet').waitFor({ state: 'detached' });
  await beside.waitForTimeout(300);
  assert.equal(await hashOf(beside), '#/hub', 'the card is still open');
  await beside.keyboard.press('Escape');
  await beside.waitForFunction(() => /library$/.test(location.hash));

  step('two picks come back on Back after the project crumb of a card narrowed to one (the popstate half runs in the same function, restorePicks)');
  const site = await open({ width: 1200, height: 800 });
  await site.context().addInitScript(() => { try { localStorage.setItem('buw.menuCollapsed', '0'); } catch { /* none */ } });
  await site.goto(`${fixture.url}#/~hub/library`);
  await site.locator('[data-library] .lib-scroll').waitFor();
  await pickProject(site, 'Two');
  await pickProject(site, 'Three');
  assert.equal(await label(site), '2 projects');
  await site.locator('.lib-row-main', { hasText: 'Zebra crossing' }).click();
  await site.locator('.buw-markdown h1', { hasText: 'Zebra crossing' }).waitFor();
  await site.locator('.topbar .breadcrumb button.crumb-link').click();
  await site.waitForFunction(() => /library$/.test(location.hash));
  await site.waitForFunction(() => document.querySelector('[data-project-filter]')?.textContent.trim() === 'Two');
  await site.goBack();
  await site.goBack();
  await site.locator('[data-library] .lib-scroll').waitFor();
  await site.waitForTimeout(300);
  assert.equal(await label(site), '2 projects', 'Back brings the two picks back');

  step('the Library tab from a card whose history has extra entries (a page inside a frame navigated) still reaches the list');
  await phone.goto(`${fixture.url}#/~hub/library`);
  await phone.locator('[data-library] .lib-search input').waitFor();
  await phone.locator('[data-library] .lib-search input').fill('giraffe');
  await phone.locator('.lib-row-main', { hasText: 'Giraffe 1' }).first().tap();
  await phone.locator('.buw-markdown h1', { hasText: 'Giraffe 1' }).waitFor();
  await phone.evaluate(() => history.pushState(history.state, '', location.href));
  await phone.locator('[data-tabs] [data-nav="library"]').tap();
  await phone.locator('[data-library] .lib-scroll').waitFor();
  await phone.waitForTimeout(900);
  assert.match(await hashOf(phone), /#\/~hub\/library$/, 'the list opened');
  assert.equal(await phone.locator('[data-library] .lib-search input').inputValue(), 'giraffe', 'with the search it last had');

  assert.deepEqual(errors, [], 'no page errors');
  console.log('library-phone-ui: passed');
} finally {
  for (const context of contexts) await context.close().catch(() => {});
  await browser.close();
  await fixture.close();
}
